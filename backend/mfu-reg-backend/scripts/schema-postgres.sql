CREATE TABLE users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code varchar(20), full_name varchar(150) NOT NULL,
  email varchar(100) NOT NULL, password_hash varchar(255) NOT NULL,
  role varchar(20) DEFAULT 'student' CHECK (role IN ('student','lecturer','admin')),
  is_active smallint DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  must_change_password smallint NOT NULL DEFAULT 0 CHECK (must_change_password IN (0,1))
);
CREATE UNIQUE INDEX users_email_unique ON users (lower(email));
CREATE UNIQUE INDEX users_student_code_unique ON users (lower(student_code));

CREATE TABLE activity_categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name varchar(100) NOT NULL, description text,
  is_active smallint DEFAULT 1 CHECK (is_active IN (0,1))
);
CREATE UNIQUE INDEX categories_name_unique ON activity_categories (lower(category_name));

CREATE TABLE network_zones (
  zone_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_name varchar(100) NOT NULL, description text,
  is_active smallint DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE allowed_ips (
  ip_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id integer NOT NULL REFERENCES network_zones(zone_id) ON DELETE CASCADE,
  ip_range varchar(50) NOT NULL, description varchar(255),
  UNIQUE (zone_id, ip_range)
);

CREATE TABLE activities (
  activity_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizer_id integer NOT NULL REFERENCES users(user_id),
  category_id integer NOT NULL REFERENCES activity_categories(category_id),
  zone_id integer REFERENCES network_zones(zone_id),
  title varchar(255) NOT NULL, description text, cover_image varchar(500),
  location varchar(255) NOT NULL, start_at timestamp NOT NULL, end_at timestamp NOT NULL,
  registration_deadline timestamp, max_participants integer,
  points integer NOT NULL DEFAULT 0,
  requires_registration smallint DEFAULT 1 CHECK (requires_registration IN (0,1)),
  requires_wifi smallint DEFAULT 1 CHECK (requires_wifi IN (0,1)),
  status varchar(20) DEFAULT 'draft' CHECK (status IN ('draft','published','ongoing','completed','cancelled')),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX activities_category_idx ON activities(category_id);
CREATE INDEX activities_zone_idx ON activities(zone_id);
CREATE INDEX activities_status_idx ON activities(status);
CREATE INDEX activities_start_idx ON activities(start_at);
CREATE INDEX activities_organizer_idx ON activities(organizer_id);

CREATE TABLE activity_registrations (
  registration_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activity_id integer NOT NULL REFERENCES activities(activity_id),
  user_id integer NOT NULL REFERENCES users(user_id),
  status varchar(20) DEFAULT 'registered' CHECK (status IN ('registered','cancelled','attended','absent')),
  registered_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(activity_id, user_id)
);
CREATE INDEX registrations_user_idx ON activity_registrations(user_id);

CREATE TABLE qr_tokens (
  qr_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activity_id integer NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
  token_hash varchar(255) NOT NULL UNIQUE,
  starts_at timestamp NOT NULL, expires_at timestamp NOT NULL,
  is_active smallint DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX qr_activity_idx ON qr_tokens(activity_id);

CREATE TABLE activity_checkins (
  checkin_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activity_id integer NOT NULL REFERENCES activities(activity_id),
  user_id integer NOT NULL REFERENCES users(user_id),
  registration_id integer REFERENCES activity_registrations(registration_id) ON DELETE SET NULL,
  qr_id integer NOT NULL REFERENCES qr_tokens(qr_id),
  verified_ip varchar(45),
  verification_status varchar(20) DEFAULT 'verified' CHECK (verification_status IN ('verified','rejected')),
  checked_in_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(activity_id,user_id)
);
CREATE INDEX checkins_registration_idx ON activity_checkins(registration_id);
CREATE INDEX checkins_qr_idx ON activity_checkins(qr_id);
CREATE INDEX checkins_user_idx ON activity_checkins(user_id);

CREATE TABLE point_transactions (
  transaction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(user_id),
  activity_id integer REFERENCES activities(activity_id) ON DELETE SET NULL,
  checkin_id integer UNIQUE REFERENCES activity_checkins(checkin_id) ON DELETE SET NULL,
  points integer NOT NULL,
  transaction_type varchar(20) NOT NULL CHECK (transaction_type IN ('earn','revoke','adjust')),
  description varchar(255), created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX transactions_activity_idx ON point_transactions(activity_id);
CREATE INDEX transactions_user_idx ON point_transactions(user_id);
CREATE INDEX transactions_date_idx ON point_transactions(created_at);

CREATE FUNCTION mfu333_set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION mfu333_set_updated_at();
CREATE TRIGGER activities_updated_at BEFORE UPDATE ON activities
  FOR EACH ROW EXECUTE FUNCTION mfu333_set_updated_at();
CREATE TRIGGER registrations_updated_at BEFORE UPDATE ON activity_registrations
  FOR EACH ROW EXECUTE FUNCTION mfu333_set_updated_at();
