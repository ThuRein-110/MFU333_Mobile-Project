/// Thai is the original interface language. User-entered content stays as saved.
/// Keep interface translations here, and translate API messages only for display.
extension AppStrings on BuildContext {
  String tr(String source, {Map<String, String> args = const {}}) {
    final english = AppLanguageScope.maybeOf(this)?.locale.languageCode == 'en';
    var value = english
        ? (_english[source] ?? source)
        : (_thaiMessages[source] ?? source);
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

  String fieldLabel(String key) => tr(_fields[key] ?? key.replaceAll('_', ' '));
  String statusLabel(Object? value) {
    final source = value?.toString() ?? '-';
    return tr(_statuses[source] ?? source);
  }
}

